/* ============================================================
   Minimal, dependency-free PDF generator for analysis reports.
   Produces a valid single/multi-page PDF (Helvetica, text only).
   ============================================================ */

const PAGE_W = 612
const PAGE_H = 792
const LINES_PER_PAGE = 44
const MARGIN = 50

/** Escape text for a PDF string literal and drop non-ASCII chars. */
function esc(text) {
  return String(text)
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)')
    .replace(/[^\x20-\x7E]/g, '?')
}

/** Wrap a paragraph to `width` chars. */
function wrap(text, width) {
  const words = String(text).split(/\s+/)
  const out = []
  let line = ''
  for (const w of words) {
    if ((line + ' ' + w).trim().length > width) {
      out.push(line.trim())
      line = w
    } else {
      line += (line ? ' ' : '') + w
    }
  }
  if (line.trim()) out.push(line.trim())
  return out
}

function buildReportLines(a) {
  const {
    overview, aiSummary, communicationMetrics, sentimentBreakdown, strengths, weaknesses,
    scoreBreakdown, talkTime, starCoverage,
  } = a
  const lines = []
  const push = (text, size = 10) => lines.push({ text, size })

  push('IntervAI — Interview Analysis Report', 16)
  push('')
  push(`Candidate: ${overview.candidate}`, 11)
  push(`Role: ${overview.role}`, 11)
  push(`Interview date: ${overview.date}    Duration: ${overview.duration}`, 11)
  push(`Overall score: ${overview.overallScore}/100    Recommendation: ${overview.recommendation}`, 11)
  push('')
  if (scoreBreakdown?.length) {
    push('SCORE BREAKDOWN (in-house weights)', 11)
    for (const p of scoreBreakdown) {
      push(`  ${p.label}: raw ${p.raw}${p.unit === '%' ? '%' : ''}  weight ${Math.round(p.weight * 100)}%  contrib ${p.contribution}`)
      push(`    ${p.reason}`)
    }
    push('')
  }
  if (talkTime) {
    push('TALK TIME (from speaker turns)', 11)
    push(`  Candidate: ${talkTime.candidateTalkPct}% (${talkTime.candidateWords} words)`)
    push(`  Interviewer: ${talkTime.interviewerTalkPct}% (${talkTime.interviewerWords} words)`)
    push(`  Unanswered questions: ${talkTime.unansweredCount}`)
    push('')
  }
  if (starCoverage) {
    push('STAR ANSWER STRUCTURE (rule-based)', 11)
    push(`  Coverage: ${starCoverage.found}/${starCoverage.total}`)
    for (const l of starCoverage.letters || []) {
      push(`  ${l.letter} ${l.name}: ${l.present ? 'found' : 'missing'}`)
    }
    push('')
  }
  if (a.scorecard?.items?.length) {
    push(`SCORECARD${a.scorecard.templateName ? ` (${a.scorecard.templateName})` : ''}`, 11)
    for (const item of a.scorecard.items) {
      push(`  ${item.label}: ${item.rating != null ? `${item.rating}/5` : 'not rated'}`)
    }
    if (a.scorecardAverage != null) push(`  Average: ${a.scorecardAverage}/5`)
    push('')
  }
  push('SENTIMENT DISTRIBUTION', 11)
  for (const b of sentimentBreakdown) push(`  ${b.name}: ${b.value}%`)
  push('')
  push('COMMUNICATION METRICS', 11)
  for (const m of communicationMetrics) push(`  ${m.label}: ${m.value} ${m.unit}  (target ${m.target})`)
  push('')
  push('STRENGTHS', 11)
  strengths.forEach((s, i) => push(`  ${i + 1}. ${s}`))
  push('')
  push('AREAS TO IMPROVE', 11)
  weaknesses.forEach((s, i) => push(`  ${i + 1}. ${s}`))
  push('')
  push('EXECUTIVE SUMMARY', 11)
  for (const t of wrap(aiSummary.executive, 96)) push(t)
  push('')
  push('RECOMMENDED ACTIONS', 11)
  aiSummary.recommendations.forEach((r, i) => push(`  ${i + 1}. ${r}`))
  push('')
  push(`Final recommendation: ${aiSummary.recommendation}`, 11)
  push('')
  push('Generated by IntervAI — AI-Powered Interview Analysis Platform')
  return lines
}

function contentStreamFor(pageLines) {
  let y = PAGE_H - 60
  let ops = 'BT\n/F1 12 Tf\n'
  for (const { text, size } of pageLines) {
    const lineHeight = size >= 14 ? 22 : size >= 11 ? 17 : 13
    ops += `1 0 0 1 ${MARGIN} ${y} Tm\n/F1 ${size} Tf\n(${esc(text)}) Tj\n`
    y -= lineHeight
  }
  ops += 'ET\n'
  return ops
}

/** Render a full analysis document to a PDF Buffer. */
export function renderReportPdf(analysis) {
  const lines = buildReportLines(analysis)
  const pages = []
  for (let i = 0; i < lines.length; i += LINES_PER_PAGE) {
    pages.push(lines.slice(i, i + LINES_PER_PAGE))
  }

  const offsets = []
  let out = '%PDF-1.4\n'

  const obj = (n, body) => {
    offsets[n] = out.length
    out += `${n} 0 obj\n${body}\nendobj\n`
  }

  const pageCount = pages.length
  const fontObj = 3 + pageCount
  const kids = pages.map((_, i) => `${3 + i} 0 R`).join(' ')

  obj(1, `<< /Type /Catalog /Pages 2 0 R >>`)
  obj(2, `<< /Type /Pages /Kids [${kids}] /Count ${pageCount} >>`)

  pages.forEach((_, i) => {
    obj(
      3 + i,
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_W} ${PAGE_H}] ` +
        `/Resources << /Font << /F1 ${fontObj} 0 R >> >> ` +
        `/Contents ${fontObj + 1 + i} 0 R >>`,
    )
  })

  obj(fontObj, `<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>`)

  pages.forEach((pageLines, i) => {
    const stream = contentStreamFor(pageLines)
    obj(fontObj + 1 + i, `<< /Length ${stream.length} >>\nstream\n${stream}endstream`)
  })

  // xref table
  const xrefStart = out.length
  out += `xref\n0 ${offsets.length}\n`
  out += `0000000000 65535 f \n`
  for (let i = 1; i < offsets.length; i++) {
    out += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`
  }
  out += `trailer\n<< /Size ${offsets.length} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`

  return Buffer.from(out, 'latin1')
}
